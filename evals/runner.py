"""Run the trap/control pairs and the learning experiment, and write the results.

    python -m evals.runner [--runs 3] [--model none|fill|fresh]

--model none (default): the rules alone. They give the same answer every time, so repeats show
  no spread; they're still run and stored so a change that makes him flaky would show.
--model fill: the model reads each email too, with saved readings (evals/cache), so only emails
  it hasn't seen cost a call.
--model fresh: the model reads every email again on every run, to measure how much its answers
  vary. This calls the API runs x scenarios times.

Writes evals/results/latest/: runs.jsonl (every run), metrics.json, pair_results.json,
learning_curve.json and report.md. Every number in the report comes from those files.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from evals import learning_experiment
from evals.adapter import Config, Scenario, run_once
from evals.trust_metrics import paired_success_rate, pairs, per_scenario, summary

HERE = Path(__file__).resolve().parent
OUT = HERE / "results" / "latest"
MODEL_CACHE = HERE / "cache" / "understanding.jsonl"


def reader_for(model: str):
    if model == "none":
        return None
    import httpx

    from oscar.understand import Reader, api_key
    if not api_key():
        raise SystemExit("Running with the model needs GEMINI_API_KEY in .env.")
    return Reader(httpx.Client(timeout=40), MODEL_CACHE if model == "fill" else None, reads="full")


def commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=HERE).stdout.strip()
    except OSError:
        return "unknown"


def pct(x) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def failure_kind(run: dict) -> str:
    g = run["grading"]
    if g["hard_floor_violation"] or g["forbidden_effect_occurred"]:
        return "safety: acted on something that needed you"
    if g["under_ask"]:
        return "under-ask: acted when it should have asked"
    if g["too_strict_safety"]:
        return "safety rule stricter than needed"
    if g["over_ask"]:
        return "over-ask: asked when it could have acted"
    if not g["action_correct"]:
        return "wrong action"
    if not g["autonomy_correct"]:
        return "wrong level"
    return "world state didn't match (the action didn't happen)"


def report(env: dict, metrics: dict, pair_rows: dict, runs: list[dict], learning: dict) -> str:
    full = metrics["FULL"]
    lines = [
        "# Evaluation Summary", "",
        "Generated by `python -m evals.runner`. Every number comes from the runs in this folder.", "",
        "## Environment", "",
        f"- git commit: `{env['commit']}`",
        f"- timestamp: {env['timestamp']}",
        f"- model: {env['model']}",
        f"- configurations: {', '.join(env['configs'])}",
        f"- scenarios: {env['scenarios']} ({env['pairs']} trap/control pairs)",
        f"- runs per scenario: {env['runs']} ({env['total_runs']} runs in all)",
        "- eval split: test (trap/control pairs); learning experiment: train → held-out test", "",
        "## Full system", "",
        f"- Autonomy accuracy: {pct(full['autonomy_accuracy'])}",
        f"- Trust pass rate (traps): {pct(full['trust_pass_rate'])}",
        f"- Completion: {pct(full['completion_rate'])}",
        f"- Paired trap/control success: {pct(full['paired_success_rate'])}",
        f"- Over-ask (asked when acting was right): {pct(full['over_ask_rate'])}",
        f"- Under-ask (acted when asking was right): {pct(full['under_ask_rate'])}",
        f"- Unsafe side effects: {pct(full['unsafe_side_effect_rate'])} ({full['unsafe_side_effects_executed']} executed)",
        f"- Prompt injection success: {pct(full['prompt_injection_success_rate'])}",
        f"- Hard-floor violations: {full['hard_floor_violations']}",
        f"- Autonomous completion: {pct(full['autonomous_completion_rate'])}",
        f"- Interruption rate: {pct(full['interruption_rate'])}",
        f"- Calibration: Brier {full['brier']}, ECE {full['ece']}", "",
        "## Ablation", "",
        "| | Baseline | Safety only | Full | Learning, safety off |",
        "|---|---|---|---|---|",
    ]
    cols = ["BASELINE", "SAFETY_ONLY", "FULL", "LEARNING_ONLY"]
    for label, key, fmt in [("Autonomy", "autonomy_accuracy", pct), ("Trust", "trust_pass_rate", pct),
                            ("Completion", "completion_rate", pct), ("Paired success", "paired_success_rate", pct),
                            ("Unsafe effects", "unsafe_side_effect_rate", pct), ("Hard-floor violations", "hard_floor_violations", str),
                            ("Prompt injection success", "prompt_injection_success_rate", pct),
                            ("Over-ask", "over_ask_rate", pct), ("Under-ask", "under_ask_rate", pct),
                            ("Interruptions", "interruption_rate", pct)]:
        lines.append(f"| {label} | " + " | ".join(fmt(metrics[c][key]) for c in cols) + " |")
    lines += ["", "Baseline: no safety rules, nothing learned. Safety only: the rules, nothing learned. Full: both. "
              "Learning, safety off: what the user taught with the floor and checks turned off, which shows what "
              "the floor stops. Safety-off setups only ever run in the simulated inbox.", ""]

    s = learning["summary"]
    lines += [
        "## Learning", "",
        f"Fresh memory, then {s['training_emails']} training emails over {len(learning['curve']) - 1} rounds "
        f"({s['feedback_events']} pieces of feedback from a simulated user, through the app's own feedback). "
        "The held-out set (new emails from the same senders, new senders at the same domains, new senders of "
        "the same kinds, and traps) runs after each round on a copy of memory.", "",
        "| | Before feedback | After feedback |", "|---|---|---|",
        f"| ASK rate (safe emails) | {pct(s['ask_rate_before_learning'])} | {pct(s['ask_rate_after_learning'])} |",
        f"| Interruption rate | {pct(s['interruption_rate_before'])} | {pct(s['interruption_rate_after'])} |",
        f"| Autonomous completion | {pct(s['autonomous_completion_before'])} | {pct(s['autonomous_completion_after'])} |",
        f"| Action accuracy | {pct(s['action_accuracy_before'])} | {pct(s['action_accuracy_after'])} |",
        f"| Safety violations | {s['safety_violations_before']} | {s['safety_violations_after']} |", "",
        f"Interruptions down {pct(s['interruption_reduction_absolute'])} (absolute), {pct(s['interruption_reduction_relative'])} (relative). "
        f"Hard-floor violations after learning: {s['hard_floor_violations_after_learning']}. "
        f"Traps respected after learning: {s['traps_respected_after_learning']}.", "",
        "| Round | Feedback | ASK rate | Interruptions | Autonomy | Autonomous completion | Unsafe | Floor violations | Traps |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for p in learning["curve"]:
        lines.append(f"| {p['round']} | {p['feedback_events']} | {pct(p['ask_rate'])} | {pct(p['interruption_rate'])} | "
                     f"{pct(p['autonomy_accuracy'])} | {pct(p['autonomous_completion'])} | {p['unsafe_side_effects']} | "
                     f"{p['hard_floor_violations']} | {p['traps_respected']} |")

    lines += ["", "## Failures", "", "Every run of the full system that missed on level, action, trust or completion. "
              "Other setups' misses are counted in metrics.json.", ""]
    failed = [r for r in runs if r["config"] == "FULL" and not (r["grading"]["autonomy_correct"] and r["grading"]["action_correct"]
                                                                  and r["grading"]["trust_pass"] and r["grading"]["completion_pass"])]
    by_scenario: dict[str, list[dict]] = {}
    for r in failed:
        by_scenario.setdefault(r["scenario_id"], []).append(r)
    if not by_scenario:
        lines.append("None.")
    for sid, rs in by_scenario.items():
        r = rs[0]
        steps = "; ".join(f"{t['tool']}{'' if t['allowed'] else ' (blocked)'}" for t in r["trace"]) or "no calls"
        lines += [
            f"### {sid} ({len(rs)}/{env['runs']} runs)",
            f"- Expected: {r['expected']['autonomy']}" + (f", {r['expected']['action']}" if r['expected']['action'] else ""),
            f"- Observed: {r['decision']['autonomy']}, {r['decision']['proposed_action']} (set by {r['decision']['level_source']})",
            f"- Trace: {steps}",
            f"- Likely cause: {failure_kind(r)}", "",
        ]

    lines += ["## Pairs (full system)", "", "| Pair | Trap | Control | Paired success |", "|---|---|---|---|"]
    for p in pair_rows["FULL"]:
        if p["run_index"] == 1:
            lines.append(f"| {p['pair_id']} | {p['trap']} | {p['control']} | {'yes' if p['paired_success'] else 'no'} |")

    lines += ["", "## Limitations", "",
              "- The scenarios are hand-written and small (26 trap/control scenarios, 9 held-out learning emails). "
              "They show the floor holds and learning works on these cases; they don't estimate rates on a real inbox.",
              "- Expected answers are one careful person's judgement. A few (a colleague's FYI, a doc share) could "
              "reasonably go another way.",
              "- Oscar's tools can only mark read, archive and label, so unsafe effects like sending or paying can't "
              "happen in this system at all. Unsafe effects are measured as what he decided to do on his own "
              "(blocked by the tool layer) plus any change in the world.",
              "- 'Explicit authorization' controls aren't tested: Oscar has no way to take a one-time authorization "
              "to send, so approving an ask is the only authorization path.",
              "- With the rules alone, repeats can't vary, so the 3 runs per scenario only guard against flakiness. "
              "Variance from the model needs `--model fresh`.",
              "- The learning experiment uses a simulated user who always wants newsletters and promos archived. "
              "Real people are less consistent.",
              "- Confidence (for Brier and ECE) is how sure Oscar is of the level he chose, not a probability spread over all four levels.",
              ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs", type=int, default=3)
    parser.add_argument("--model", choices=["none", "fill", "fresh"], default="none")
    args = parser.parse_args()
    reader = reader_for(args.model)

    scenarios = [Scenario.model_validate(s) for s in json.loads((HERE / "scenarios" / "trust_pairs.json").read_text())]
    assert all(s.split == "test" for s in scenarios), "the trap/control pairs are test data only"
    configs = [Config.BASELINE, Config.SAFETY_ONLY, Config.FULL, Config.LEARNING_ONLY]
    runs = [run_once(s, c, i, reader) for c in configs for s in scenarios for i in range(1, args.runs + 1)]
    learning = learning_experiment.run(runs=args.runs, reader=reader)

    metrics, pair_rows = {}, {}
    for c in configs:
        mine = [r for r in runs if r["config"] == c.value]
        pair_rows[c.value] = pairs(mine)
        metrics[c.value] = {**summary(mine), "paired_success_rate": paired_success_rate(pair_rows[c.value]),
                            "per_scenario": per_scenario(mine)}
    env = {"commit": commit(), "timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
           "model": "rules only" if args.model == "none" else f"{args.model} (gemini)", "configs": [c.value for c in configs],
           "scenarios": len(scenarios), "pairs": len({s.pair_id for s in scenarios}), "runs": args.runs, "total_runs": len(runs)}

    OUT.mkdir(parents=True, exist_ok=True)
    with (OUT / "runs.jsonl").open("w") as f:
        for r in runs:
            f.write(json.dumps(r) + "\n")
    (OUT / "metrics.json").write_text(json.dumps({"environment": env, "configs": metrics}, indent=1) + "\n")
    (OUT / "pair_results.json").write_text(json.dumps(pair_rows, indent=1) + "\n")
    (OUT / "learning_curve.json").write_text(json.dumps({"curve": learning["curve"], "summary": learning["summary"]}, indent=1) + "\n")
    (OUT / "report.md").write_text(report(env, metrics, pair_rows, runs, learning))
    full = metrics["FULL"]
    print(f"Full: autonomy {pct(full['autonomy_accuracy'])}, trust {pct(full['trust_pass_rate'])}, "
          f"paired {pct(full['paired_success_rate'])}, hard-floor violations {full['hard_floor_violations']}")
    print(f"Learning: interruptions {pct(learning['summary']['interruption_rate_before'])} -> "
          f"{pct(learning['summary']['interruption_rate_after'])}, violations after {learning['summary']['hard_floor_violations_after_learning']}")
    print(f"Wrote {OUT.relative_to(HERE.parent)}/ ({len(runs)} runs). {Counter(r['config'] for r in runs)}")


if __name__ == "__main__":
    main()
