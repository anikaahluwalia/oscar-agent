"""Measure Oscar: python -m evals.measure [--policy default-p1] [--emails 400] [--seed 1]

1. Learn: run the generated learning inbox with a simulated user, keep the feedback.
2. Check for leakage between the learning set and the eval sets. Stop if there is any.
3. Score, with learning frozen:
     held-out before learning, held-out after learning,
     safety before and after learning, and the regression cases.
4. Save every run (evals/results/runs/) and write evals/results/REPORT.md.

Exits with 1 if the build is unsafe or regressed, so it can gate a change.
"""

import argparse
import sys

from evals import harness, report
from evals.learning import learn, leaks
from oscar.preferences import POLICIES


def measure(policy_name: str = "default-p1", emails: int = 400, seed: int = 1, save: bool = True) -> dict:
    policy = POLICIES[policy_name]
    heldout_path, safety_path = harness.CASES / "heldout_v1.jsonl", harness.CASES / "safety_v1.jsonl"
    heldout, safety = harness.load(heldout_path), harness.load(safety_path)
    regression = harness.regression_suite()

    events, stream = learn(emails, seed, policy)
    problems = leaks(heldout + safety + regression, stream)
    if problems:
        raise SystemExit("Leakage between the learning set and the eval sets:\n  " + "\n  ".join(problems[:20]))
    info = {"set": "learning_v1 (generated by evals/dataset.py)", "emails": emails, "seed": seed, "feedback": len(events),
            "templates": len({i.template for i in stream})}

    h_info, s_info = harness.dataset_info(heldout_path, heldout), harness.dataset_info(safety_path, safety)
    reg_info = {"name": "regression_cases", "cases": len(regression), "sha256": "-"}
    runs = {
        "heldout_before": harness.run_suite("heldout", heldout, h_info, None, None, policy),
        "heldout_after": harness.run_suite("heldout", heldout, h_info, events, info, policy),
        "safety_before": harness.run_suite("safety", safety, s_info, None, None, policy),
        "safety_after": harness.run_suite("safety", safety, s_info, events, info, policy),
        "regression": harness.run_suite("regression", regression, reg_info, events, info, policy),
    }
    if save:
        for run in runs.values():
            harness.save(run)
        (harness.HERE / "results" / "REPORT.md").write_text(report.render(runs))
    return runs


def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m evals.measure")
    parser.add_argument("--policy", default="default-p1", choices=sorted(POLICIES))
    parser.add_argument("--emails", type=int, default=400)
    parser.add_argument("--seed", type=int, default=1)
    args = parser.parse_args()
    runs = measure(args.policy, args.emails, args.seed)
    print(report.render(runs))
    problems = report.gate(runs)
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
